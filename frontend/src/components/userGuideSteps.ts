/** 一条要点 = **一个短标签 + 一句说明**。
 *
 * 为什么要拆成两段而不是一整句：这一步有几十条要点，用户是"扫"而不是"读"的——
 * 先说清楚有哪些事（`lead` 加粗、2–8 字），想细看再看 `text`。
 * 此前每条都是一整段话（有的近百字），八十多条排在一起就成了一堵墙，
 * 截图反馈"密密麻麻、抓不到重点"。
 */
export interface GuidePoint {
  /** 粗体短标签，2–8 字。用"用户会怎么称呼这件事"，不要用功能内部名。 */
  lead: string;
  /** 一句话说清。**控制在一句**，第二句就该另起一条。 */
  text: string;
}

export interface GuideStep {
  title: string;
  heading: string;
  description: string;
  points: GuidePoint[];
  path: string;
  actionLabel: string;
  icon: ComponentType;
}

